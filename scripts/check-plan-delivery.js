#!/usr/bin/env node
// Plan Delivery Check — verifies that what a TASK plan DECLARED was actually DELIVERED.
// Repo infrastructure (not part of the governed-project payload): it reads this repo's
// plan documents and cross-checks their claims against the working tree.
//
// Why this exists: "plan completed" used to be the agent's self-assessment, so a plan could
// be archived while parts of its Affected Files / Validation Method were never delivered
// (real case: sync-groups-mechanical-check declared a `sync.passed` release precondition
// that was never added). This check turns that judgement into a mechanical comparison.
//
// Plans may also declare BEHAVIOUR (not just files), which path checks cannot verify:
//   - writes: `<file>` in `<script>`      (e.g. writes: `drift-report.json` in `scripts/check-sync.js`)
//   - wires:  `<identifier>` in `<file>`
// 中文同义词亦可：写入/接线。
//
// Usage:
//   node scripts/check-plan-delivery.js [--json] [--gate] [--plan <file>]
// Exit 0: every declared item is delivered (or --advisory default when not --gate).
// Exit 1: undelivered declarations found (only in --gate mode, or always with --gate).

const fs = require("fs");
const path = require("path");

const ROOT = process.cwd();
const TREES = ["en", "zh-CN", "zh-TW"];

// ---------------------------------------------------------------------------
// Normalisation rules — the source of false positives if left implicit.
// Each rule maps a DECLARED path to how it should actually be verified.
// Keep this table maintained: new equivalences go here, not into ad-hoc code.
// ---------------------------------------------------------------------------
const RUNTIME_ARTIFACTS = [
  // Declared path fragment -> file that must contain the generating/declaring logic
  [".governance/validation.json", ["scripts/verify_governance.js", "references/policies/governance-files.policy.md"]],
  [".governance/drift-report.json", ["scripts/check-doc-consistency.js", "scripts/check-doc-freshness.js"]],
  [".governance/release-proposal.json", ["scripts/release-manager.js", "references/workflows/release.md"]],
  [".governance/activity.jsonl", ["references/policies/governance-files.policy.md", "references/templates/sub-skills.md"]],
  [".governance/state.json", ["references/templates/sub-skills.md", "scripts/generate-governance.js"]],
  [".governance/manifest.json", ["scripts/generate-governance.js", "scripts/verify_governance.js"]],
  [".governance/git-policy.json", ["references/templates/git-policy.template.md", "scripts/verify_governance.js"]],
  [".governance/sync-rules.json", ["references/templates/sync-rules.template.md", "scripts/check-sync.js"]],
  [".governance/preflight.json", ["scripts/generate-governance.js", "scripts/verify_governance.js"]],
  [".governance/generated/skills", ["references/templates/sub-skills.md"]],
];

// Files that live only inside GOVERNED projects (generated by INIT), verified via their template
const GOVERNED_ONLY = [
  ["docs/ARCHITECTURE.md", ["references/init-spec.json"]],
  ["docs/features", ["references/templates/feature-doc.template.md", "references/init-spec.json"]],
  ["docs/plans/DEVELOPMENT_PLAN.md", ["references/init-spec.json"]],
  ["docs/plans/archive", ["references/workflows/release.md"]],
  ["docs/rules", ["references/init-spec.json"]],
  ["docs/rules/**", ["references/init-spec.json", "references/policies/lifecycle.policy.md"]],
  [".env.example", ["references/templates/env-example.template.md"]],
  [".gitmessage.txt", ["references/templates/gitmessage.template.md"]],
  ["scripts/verify-governance.js", ["scripts/verify_governance.js"]],
];

function readFileSafe(p) {
  try {
    return fs.readFileSync(path.join(ROOT, p), "utf8");
  } catch {
    return null;
  }
}

function existsAny(candidates) {
  return candidates.some((c) => fs.existsSync(path.join(ROOT, c)));
}

// Expand docs/x.md -> docs/{en,zh-CN,zh-TW}/x.md ; also handle {a,b} globs and ** wildcards
function candidatePaths(declared) {
  const out = [];
  let d = declared.trim().replace(/^`|`$/g, "");
  if (!d) return out;

  // brace expansion: docs/{en,zh-CN,zh-TW}/commands.md
  const brace = d.match(/^(.*)\{([^}]+)\}(.*)$/);
  if (brace) {
    for (const part of brace[2].split(",")) out.push(brace[1] + part.trim() + brace[3]);
  } else {
    out.push(d);
  }

  const expanded = [];
  for (let c of out) {
    c = c.replace(/\*\*\/?/g, "").replace(/\*/g, "").replace(/\/+$/, "");
    if (!c) continue;
    expanded.push(c);
    // docs/foo.md may actually live in the three language trees
    const m = c.match(/^docs\/([^/]+\.md)$/);
    if (m) for (const t of TREES) expanded.push("docs/" + t + "/" + m[1]);
    const m2 = c.match(/^docs\/plans\/(.+)$/);
    if (m2) {
      for (const t of TREES) expanded.push("docs/" + t + "/plans/" + m2[1]);
      expanded.push("docs/archive/" + m2[1]); // archived at release
    }
    // archived plan may have moved out of the language trees
    const m3 = c.match(/^docs\/(?:en|zh-CN|zh-TW)\/plans\/(.+)$/);
    if (m3) expanded.push("docs/archive/" + m3[1]);
    // Bare filename with no directory: resolve against the known homes. Plans often cite
    // just "sync-rules.template.md" instead of "references/templates/sync-rules.template.md".
    if (!c.includes("/")) {
      for (const home of ["references/templates", "references/policies", "references/workflows", "scripts", "tests", "docs", "docs/archive"]) {
        expanded.push(home + "/" + c);
      }
    }
  }
  return [...new Set(expanded)];
}

function verifyDeclaredPath(declared) {
  const raw = declared.trim().replace(/^`|`$/g, "");

  for (const [frag, proofs] of RUNTIME_ARTIFACTS) {
    // Match a declared path to an artifact fragment by exact path, by a path-BOUNDARY
    // prefix (".governance/generated/skills" is a directory fragment, so files beneath it
    // are the same artifact — but ".../validation.json.bak" is NOT), or by basename
    // (a plan often cites the bare "git-policy.json" for ".governance/git-policy.json").
    const fragBase = path.basename(frag);
    const matchesFrag = raw === frag || raw.startsWith(frag + "/") || raw === fragBase || raw.endsWith("/" + fragBase);
    if (matchesFrag) {
      const found = proofs.filter((pf) => {
        const c = readFileSafe(pf);
        return c && c.includes(path.basename(frag));
      });
      return found.length > 0
        ? { ok: true, how: "runtime artifact declared in " + found[0] }
        : { ok: false, how: "runtime artifact: no generating/declaring logic found in " + proofs.join(", ") };
    }
  }

  for (const [frag, proofs] of GOVERNED_ONLY) {
    if (raw === frag || raw.replace(/\/+$/, "") === frag) {
      const found = proofs.filter((pf) => fs.existsSync(path.join(ROOT, pf)));
      return found.length > 0
        ? { ok: true, how: "governed-project artifact backed by " + found[0] }
        : { ok: false, how: "governed-project artifact: template/spec missing (" + proofs.join(", ") + ")" };
    }
  }

  const cands = candidatePaths(raw);
  if (cands.length === 0) return { ok: true, how: "not a path" };
  if (existsAny(cands)) return { ok: true, how: "exists" };
  return { ok: false, how: "not found (tried: " + cands.slice(0, 4).join(", ") + ")" };
}

// Identifiers declared in a plan (e.g. `sync.passed`, `task_start_sha`) must be findable
// somewhere in the payload/infrastructure — otherwise the promise was never wired in.
const IDENTIFIER_RE = /^[a-z][a-z0-9_]*(?:[._][a-z0-9_]+)+$/i;
const SEARCH_ROOTS = ["references", "scripts", "tests", "AGENTS.md", "SKILL.md", "package.json", "CHANGELOG.md"];

function walkFiles(rel) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) return [];
  const st = fs.statSync(abs);
  if (st.isFile()) return [rel];
  const out = [];
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    out.push(...walkFiles(path.join(rel, e.name)));
  }
  return out;
}

let searchCorpus = null;
function corpus() {
  if (searchCorpus) return searchCorpus;
  searchCorpus = [];
  for (const r of SEARCH_ROOTS) {
    for (const f of walkFiles(r)) {
      // Exclude the checker's own source and CHANGELOG: a comment naming an identifier (or a
      // changelog entry describing a bug about it) is not evidence the identifier is WIRED
      // in. Self-reference and historical description both create false "verified" hits.
      if (f === "scripts/check-plan-delivery.js" || f === "CHANGELOG.md") continue;
      const c = readFileSafe(f);
      if (c) searchCorpus.push([f, c]);
    }
  }
  return searchCorpus;
}

function verifyIdentifier(id) {
  const hits = corpus().filter(([, c]) => c.includes(id));
  return hits.length > 0
    ? { ok: true, how: "found in " + hits[0][0] }
    : { ok: false, how: "identifier never wired in (searched references/, scripts/, tests/, root docs)" };
}

// Behavioural declarations: "writes: X in Y" / "wires: X in Y" (also 写入/接线).
// These catch promises that path-existence checks cannot (e.g. "appends to drift-report.json").
const BEHAVIOUR_RE = /(?:writes|wires|写入|接线)\s*[:：]\s*`([^`]+)`\s*(?:in|于|进)\s*`([^`]+)`/gi;

function verifyBehaviours(content) {
  const out = [];
  let m;
  BEHAVIOUR_RE.lastIndex = 0;
  while ((m = BEHAVIOUR_RE.exec(content))) {
    const what = m[1].trim();
    const where = m[2].trim();
    const target = readFileSafe(where);
    if (target === null) {
      out.push({ kind: "behaviour", item: what + " in " + where, detail: "target file not found: " + where });
      continue;
    }
    const needle = what.includes("/") ? path.basename(what) : what;
    if (!target.includes(needle)) {
      out.push({ kind: "behaviour", item: what + " in " + where, detail: "declared behaviour not implemented (\"" + needle + "\" absent from " + where + ")" });
    }
  }
  return out;
}

function extractSection(content, names) {
  // Accept the heading at H2-H4 and return EVERY matching section concatenated.
  //
  // Two defects this shape avoids:
  //   1. The anchor used to be a literal "###", which matches inside "####" but never
  //      inside "##" — a plan written with `## Affected Files` extracted nothing while the
  //      script still printed "every declared path delivered". That is the heading level
  //      the shipped plan template uses, so such plans were unverifiable.
  //   2. Returning only the FIRST matching level then dropped the other one: a plan with
  //      both `## Affected Files` and a later `### Affected Files` had its H2 declarations
  //      silently discarded (review finding). Same for two sections at the same level.
  // Each match stops at the next heading of the SAME OR HIGHER level, so deeper
  // subsections stay inside their section and a sibling section is never absorbed.
  const parts = [];
  for (const h of ["##", "###", "####"]) {
    const depth = h.length;
    // The heading must start a line and carry EXACTLY this depth: `(?:^|\n)` anchors it,
    // and the `(?!#)` guard stops "##" from also matching the "##" prefix of "###".
    const re = new RegExp(
      "(?:^|\\n)" + h + "(?!#)\\s*(?:" + names.join("|") + ")([\\s\\S]*?)(?=\\n#{1," + depth + "}(?!#)\\s|$)",
      "gi"
    );
    let m;
    while ((m = re.exec(content))) parts.push(m[1]);
  }
  return parts.length > 0 ? parts.join("\n") : null;
}

// A plan that openly declares itself design-only / not implemented is out of delivery
// scope: nothing is supposed to be delivered yet. Archived plans are ALWAYS in scope
// (archiving asserts completion).
function isDesignOnly(relPath, content) {
  // Archived plans are always in scope: archiving asserts completion.
  if (relPath.replace(/\\/g, "/").includes("docs/archive/")) return false;
  // Otherwise rely on an EXPLICIT status marker near the top of the plan
  // (`Status: design plan, not implemented` / `状态：设计计划，未实现` / `狀態：設計計劃，未實作`).
  const head = content.split(/\r?\n/).slice(0, 12).join("\n");
  return /Status:\s*design plan, not implemented|状态：设计计划，未实现|狀態：設計計劃，未實作/i.test(head);
}

function auditPlan(relPath) {
  const content = readFileSafe(relPath);
  if (!content) return null;
  if (isDesignOnly(relPath, content)) return { plan: relPath, findings: [], skipped: "design-only (not implemented yet)" };
  const findings = [];

  // tokens already covered by a behavioural declaration are excluded from path checks
  const behaviourTokens = new Set();
  {
    let bm;
    BEHAVIOUR_RE.lastIndex = 0;
    while ((bm = BEHAVIOUR_RE.exec(content))) {
      behaviourTokens.add(bm[1].trim());
      behaviourTokens.add(bm[2].trim());
    }
  }

  const af = extractSection(content, ["受影响文件", "Affected Files", "受影響檔案"]);
  if (af) {
    const ticked = [...new Set((af.match(/`([^`]+)`/g) || []).map((s) => s.slice(1, -1)))]
      .filter((t) => !behaviourTokens.has(t));
    for (const t of ticked) {
      if (t.includes(" ") || t.startsWith("--")) continue;
      const looksPath = /[\/]/.test(t) || /\.[a-z]{2,4}$/i.test(t);
      const looksId = IDENTIFIER_RE.test(t) && !looksPath;
      if (looksPath) {
        const r = verifyDeclaredPath(t);
        if (!r.ok) findings.push({ kind: "path", item: t, detail: r.how });
      } else if (looksId) {
        const r = verifyIdentifier(t);
        if (!r.ok) findings.push({ kind: "identifier", item: t, detail: r.how });
      }
    }
  }

  findings.push(...verifyBehaviours(content));

  return { plan: relPath, findings };
}

function main() {
  const json = process.argv.includes("--json");
  const gate = process.argv.includes("--gate");
  const only = (() => {
    const i = process.argv.indexOf("--plan");
    return i >= 0 && i + 1 < process.argv.length ? process.argv[i + 1] : null;
  })();

  const plans = [];
  if (only) {
    if (!fs.existsSync(path.join(ROOT, only))) {
      console.log("✗ plan not found: " + only);
      process.exit(1);
    }
    plans.push(only);
  } else {
    // plans still in flight (language trees) + already archived
    for (const t of TREES) {
      const dir = path.join(ROOT, "docs", t, "plans");
      if (fs.existsSync(dir)) {
        for (const f of fs.readdirSync(dir)) {
          if (f.endsWith(".md")) plans.push(path.join("docs", t, "plans", f));
        }
      }
    }
    const arch = path.join(ROOT, "docs", "archive");
    if (fs.existsSync(arch)) {
      for (const f of fs.readdirSync(arch)) {
        if (f.endsWith(".md") && !/^v\d/.test(f)) plans.push(path.join("docs", "archive", f));
      }
    }
  }

  const results = [];
  let skippedCount = 0;
  for (const p of plans) {
    const r = auditPlan(p);
    if (r && r.skipped) skippedCount++;
    if (r && r.findings.length > 0) results.push(r);
  }

  const total = results.reduce((n, r) => n + r.findings.length, 0);

  if (json) {
    process.stdout.write(JSON.stringify({ plansScanned: plans.length, designOnlySkipped: skippedCount, undelivered: total, results }, null, 2) + "\n");
  } else if (total === 0) {
    console.log("✓ plan delivery verified (" + plans.length + " plans scanned, " + skippedCount + " design-only skipped, every declared path/identifier delivered)");
  } else {
    console.log("✗ undelivered declarations (" + total + " across " + results.length + " plans):");
    for (const r of results) {
      console.log("  " + r.plan);
      for (const f of r.findings) console.log("    - [" + f.kind + "] " + f.item + " — " + f.detail);
    }
    console.log("\nFix: deliver the declaration, or correct the plan if the declaration is obsolete.");
  }

  process.exit(total > 0 && gate ? 1 : 0);
}

main();
